import { createRequire } from 'node:module';

const { PrayTime } = createRequire(import.meta.url)('praytime');

const places = [
  ['Makkah', 21.4225, 39.8262],
  ['Toronto', 43.65, -79.38],
  ['London', 51.5074, -0.1278],
  ['Tehran', 35.69, 51.39],
  ['Jakarta', -6.2088, 106.8456],
  ['Cairo', 30.0444, 31.2357],
  ['Karachi', 24.8607, 67.0011],
  ['Sydney', -33.8688, 151.2093],
  ['Istanbul', 41.0082, 28.9784],
  ['Kuala Lumpur', 3.139, 101.6869],
  ['Los Angeles', 34.0522, -118.2437],
  ['Moscow', 55.7558, 37.6173],
  ['Auckland', -36.8485, 174.7633],
  ['Honolulu', 21.3069, -157.8583],
  ['Helsinki', 60.1699, 24.9384],
  ['Reykjavik', 64.1466, -21.9426],
  ['Tromso', 69.65, 18.96],
  ['Ushuaia', -54.8019, -68.303],
];

const highLatitudePlaces = new Set(['Helsinki', 'Reykjavik', 'Tromso', 'Ushuaia']);

const dates = [
  [2026, 1, 15], [2026, 3, 1], [2026, 4, 15], [2026, 6, 15],
  [2026, 9, 28], [2026, 12, 15], [2000, 1, 1], [2050, 12, 31],
];

const methods = ['MWL', 'ISNA', 'Egypt', 'Makkah', 'Karachi', 'Tehran', 'Jafari', 'France', 'Russia', 'Singapore'];
const labels = ['fajr', 'sunrise', 'dhuhr', 'asr', 'sunset', 'maghrib', 'isha', 'midnight'];

const umAlQuraMonth = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', { month: 'numeric', timeZone: 'UTC' });
const isRamadan = ([year, month, day]) => umAlQuraMonth.format(new Date(Date.UTC(year, month - 1, day, 12))) === '9';

function minutes([, latitude, longitude], method, asr, highLats, date) {
  const praytime = new PrayTime(method).location([latitude, longitude]).adjust({ asr, highLats }).format('x');
  if (method === 'Makkah' && isRamadan(date)) praytime.adjust({ isha: '120 min' });
  const times = praytime.times(date);
  return labels.map((label) => (typeof times[label] === 'number' ? String(times[label] / 60000) : 'none'));
}

const lines = [];
const emit = (place, method, asr, highLats, date) => {
  const [name, latitude, longitude] = place;
  const values = minutes(place, method, asr, highLats, date).join(', ');
  lines.push(`{ "${name}", ${latitude}, ${longitude}, M::${method}, A::${asr}, H::${highLats}, ${date.join(', ')}, { ${values} } },`);
};

for (const place of places) {
  for (const date of dates) {
    for (const method of methods) emit(place, method, 'Standard', 'NightMiddle', date);
    emit(place, 'MWL', 'Hanafi', 'NightMiddle', date);
    emit(place, 'ISNA', 'Hanafi', 'NightMiddle', date);
    if (highLatitudePlaces.has(place[0])) {
      for (const method of ['MWL', 'ISNA', 'Makkah', 'Tehran', 'Jafari']) {
        for (const highLats of ['None', 'OneSeventh', 'AngleBased']) emit(place, method, 'Standard', highLats, date);
      }
    }
  }
}

process.stdout.write(`// Generated by tests/reference/generate.mjs from praytime.js 3.2.0. Times are minutes since 1970.\n${lines.join('\n')}\n`);
